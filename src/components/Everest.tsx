import { useEffect, useMemo } from "react";
import { Center, useGLTF } from "@react-three/drei";
import { useFrame, type ThreeElements } from "@react-three/fiber";
import { Box3, Color, MeshStandardMaterial, Vector3, type Mesh, type Object3D } from "three";
import { DRACO_PATH, MODEL_URL, MODEL_URL_LIGHT } from "../lib/heroModel";
import { IDLE_BREATHE } from "./hero-terrain/shared";

export { DRACO_PATH, MODEL_URL, MODEL_URL_LIGHT } from "../lib/heroModel";
const TERRAIN_SPAN = 420;
/**
 * Planet-curvature radius (world units). Terrain edges bend down like the Earth's
 * horizon, so the map never shows a hard end — edge drop ≈ (span/2)² / (2R) ≈ 48u.
 */
const PLANET_RADIUS = 460;

type EverestGLTF = {
  nodes: {
    Object_4: Mesh;
    Object_5: Mesh;
    Object_6: Mesh;
    Object_7: Mesh;
  };
  materials: {
    Default: MeshStandardMaterial;
  };
  scene: Object3D;
};

type ThemeMode = "light" | "dark";

type EverestProps = ThreeElements["group"] & {
  theme?: ThemeMode;
  castShadow?: boolean;
  receiveShadow?: boolean;
};

function stripMaps(mat: MeshStandardMaterial) {
  mat.map = null;
  mat.normalMap = null;
  mat.roughnessMap = null;
  mat.metalnessMap = null;
  mat.aoMap = null;
  mat.emissiveMap = null;
  mat.alphaMap = null;
  mat.bumpMap = null;
  mat.displacementMap = null;
  mat.needsUpdate = true;
}

function skipRaycast() {}

export function Everest({
  theme = "light",
  castShadow = false,
  receiveShadow = false,
  ...props
}: EverestProps) {
  const isLight = theme === "light";
  const modelUrl = isLight ? MODEL_URL_LIGHT : MODEL_URL;
  const { nodes, materials, scene } = useGLTF(modelUrl, DRACO_PATH) as unknown as EverestGLTF;

  const scale = useMemo(() => {
    const size = new Vector3();
    new Box3().setFromObject(scene).getSize(size);
    const maxDim = Math.max(size.x, size.y, size.z, 0.001);
    return TERRAIN_SPAN / maxDim;
  }, [scene]);

  const geos = useMemo(
    () => [nodes.Object_4, nodes.Object_5, nodes.Object_6, nodes.Object_7],
    [nodes],
  );

  // Dark GLB is pre-bent (scripts/bake-everest-curve.mjs). Light still bends at runtime
  // so photogrammetry tangents stay exact without inflating the 11MB file.
  useMemo(() => {
    if (!isLight) return;
    const box = new Box3();
    for (const node of geos) {
      node.geometry.computeBoundingBox();
      if (node.geometry.boundingBox) box.union(node.geometry.boundingBox);
    }
    const cx = (box.min.x + box.max.x) / 2;
    const cz = (box.min.z + box.max.z) / 2;
    const rLocal = PLANET_RADIUS / Math.max(scale, 1e-6);

    for (const node of geos) {
      const geo = node.geometry;
      if (geo.userData.planetCurved) continue;
      geo.userData.planetCurved = true;

      const pos = geo.attributes.position;
      for (let i = 0; i < pos.count; i += 1) {
        const dx = pos.getX(i) - cx;
        const dz = pos.getZ(i) - cz;
        pos.setY(i, pos.getY(i) - (dx * dx + dz * dz) / (2 * rLocal));
      }
      pos.needsUpdate = true;
      geo.computeVertexNormals();
      // Dark wire has no normal maps — tangents are wasted CPU before the first frame.
      if (isLight && geo.attributes.uv && geo.index) {
        try {
          geo.computeTangents();
        } catch {
          /* non-indexed / incomplete — skip */
        }
      }
      geo.computeBoundingBox();
      geo.computeBoundingSphere();
    }
  }, [geos, scale, isLight]);

  // Dark only — light theme uses photo maps without brand wire overlay.
  const wire = useMemo(() => {
    if (isLight) return null;
    return new MeshStandardMaterial({
      color: new Color("#d4a84a"),
      emissive: new Color("#8a6424"),
      emissiveIntensity: 0.34,
      wireframe: true,
      transparent: true,
      opacity: 0.88,
      metalness: 0.05,
      roughness: 0.68,
      depthWrite: false,
      depthTest: true,
      envMapIntensity: 0,
    });
  }, [isLight]);

  const fill = useMemo(() => {
    const mat = materials.Default.clone();
    if (isLight) {
      // Keep Sketchfab photogrammetry albedo + normal + derived roughness.
      mat.color = new Color("#ffffff");
      mat.emissive = new Color("#000000");
      mat.emissiveIntensity = 0;
      
      // Fix for "plastic/metallic" look: zero metalness.
      // Roughness is kept at 1.0 so the metallicRoughnessTexture (G channel) can drive the varied specular response for snow vs rock.
      mat.metalness = 0.0;
      mat.roughness = 1.0;
      
      // Slightly lower envMap intensity to reduce overall brightness / neon effect, but keep it high enough for natural ambient light.
      mat.envMapIntensity = 0.65; 
      
      mat.normalScale?.set(1.5, 1.5);
      
      if (mat.map) {
        mat.map.anisotropy = 16;
        mat.map.needsUpdate = true;
      }
      if (mat.normalMap) {
        mat.normalMap.anisotropy = 16;
        mat.normalMap.needsUpdate = true;
      }
      if (mat.roughnessMap) {
        mat.roughnessMap.anisotropy = 8;
        mat.roughnessMap.needsUpdate = true;
      }
      
      // Removed custom FBM shader perturbation to rely fully on high-res normal/roughness maps for photorealism.
    } else {
      stripMaps(mat);
      mat.color = new Color("#050504");
      mat.emissive = new Color("#000000");
      mat.emissiveIntensity = 0;
      mat.metalness = 0.02;
      mat.roughness = 0.98;
      mat.envMapIntensity = 0;
    }
    
    mat.wireframe = false;
    mat.transparent = false;
    mat.opacity = 1;
    mat.depthWrite = true;
    mat.depthTest = true;
    mat.needsUpdate = true;
    
    return mat;
  }, [materials.Default, isLight]);

  useEffect(
    () => () => {
      wire?.dispose();
      fill.dispose();
    },
    [wire, fill],
  );

  // Soft idle breathe — mountain scale never pulses. Dark wire only.
  useFrame((state) => {
    if (!wire) return;
    const breathe = Math.sin(state.clock.elapsedTime * IDLE_BREATHE);
    wire.emissiveIntensity = 0.34 + breathe * 0.03;
    wire.opacity = 0.88 + breathe * 0.01;
  });

  return (
    // y compensates <Center> re-centring the bent mesh (edge drop lifts the middle)
    <group {...props} dispose={null} scale={scale} rotation={[0, -0.06, 0]} position={[-6, -34, -22]}>
      <Center>
        {geos.map((node, i) => (
          <mesh
            key={`fill-${i}`}
            geometry={node.geometry}
            material={fill}
            castShadow={castShadow}
            receiveShadow={receiveShadow}
            raycast={skipRaycast}
          />
        ))}
        {wire
          ? geos.map((node, i) => (
                <mesh
                  key={`wire-${i}`}
                  geometry={node.geometry}
                  material={wire}
                  castShadow={false}
                  receiveShadow={false}
                  raycast={skipRaycast}
                />
            ))
          : null}
      </Center>
    </group>
  );
}

